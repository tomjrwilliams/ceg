def df_wide(
    v: F64_2D,
    products: list[str] | None=None,
    product: str = "p"
) -> pd.DataFrame:
    n = v.shape[0]
    assert v.shape[1] == n, (n, v.shape)
    if products is not None:
        assert len(products) == n
        assert len(products) == n
    else:
        products = enumerated_labels(product, n, justify=3)
    return pd.DataFrame(
        data={
            name: v[:, i]
            for i, name in enumerate(products)
        },
        index=products
    )

def init_constant(
    n_products: int,
    v: F64_2D,
) -> Callable[[int], F64_2D]:
    assert n_products == v.shape[0]
    assert n_products == v.shape[1]
    def f(n: int) -> F64_2D:
        assert n == n_products, (n, n_products)
        return v
    return f

